-- ───────────────────────── orders ─────────────────────────
create table if not exists orders (
  id                  uuid primary key default gen_random_uuid(),
  order_no            bigint generated by default as identity (start with 1001) unique,
  user_id             uuid references auth.users on delete set null,
  customer_name       text not null,
  phone               text not null,
  email               text,
  address             jsonb not null,
  subtotal            int  not null,
  shipping_fee        int  not null default 0,
  cod_fee             int  not null default 0,
  discount            int  not null default 0,
  total               int  not null,
  coupon_code         text,
  coupon_counted      boolean not null default false,
  payment_method      text not null check (payment_method in ('razorpay','cod')),
  payment_status      text not null default 'pending'
                      check (payment_status in ('pending','paid','failed','cod_pending','refunded')),
  status              text not null default 'pending_payment'
                      check (status in ('pending_payment','confirmed','packed','shipped','delivered','cancelled')),
  razorpay_order_id   text unique,
  razorpay_payment_id text,
  courier             text,
  tracking_number     text,
  needs_review        boolean not null default false,
  stock_released      boolean not null default false,
  paid_at             timestamptz,
  shipped_at          timestamptz,
  delivered_at        timestamptz,
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now()
);
create index if not exists orders_user_idx    on orders (user_id);
create index if not exists orders_status_idx  on orders (status, created_at);
create index if not exists orders_phone_idx   on orders (phone);

create table if not exists order_items (
  id          uuid primary key default gen_random_uuid(),
  order_id    uuid not null references orders on delete cascade,
  product_id  uuid references products on delete set null,
  variant_id  uuid references product_variants on delete set null,
  name        text not null,
  color       text,
  size        text,
  image_url   text,
  price       int  not null,
  qty         int  not null check (qty between 1 and 10)
);
create index if not exists order_items_order_idx on order_items (order_id);

