-- ───────────────────────── order functions ─────────────────────────
-- place_order: order + items + stock reservation in ONE transaction.
-- Raises OUT_OF_STOCK:<variant_id> or COUPON_LIMIT; then nothing is saved.
create or replace function place_order(p_order jsonb, p_items jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_id     uuid;
  v_no     bigint;
  v_cod    boolean := (p_order->>'payment_method') = 'cod';
  v_coupon text    := nullif(p_order->>'coupon_code', '');
  v_item   jsonb;
  v_rows   int;
begin
  insert into orders (user_id, customer_name, phone, email, address, subtotal, shipping_fee,
                      cod_fee, discount, total, coupon_code, coupon_counted, payment_method,
                      payment_status, status)
  values (nullif(p_order->>'user_id','')::uuid, p_order->>'customer_name', p_order->>'phone',
          nullif(p_order->>'email',''), p_order->'address',
          (p_order->>'subtotal')::int, (p_order->>'shipping_fee')::int, (p_order->>'cod_fee')::int,
          (p_order->>'discount')::int, (p_order->>'total')::int, v_coupon,
          v_cod and v_coupon is not null, p_order->>'payment_method',
          case when v_cod then 'cod_pending' else 'pending' end,
          case when v_cod then 'confirmed' else 'pending_payment' end)
  returning id, order_no into v_id, v_no;

  for v_item in select * from jsonb_array_elements(p_items) loop
    update product_variants
       set stock = stock - (v_item->>'qty')::int
     where id = (v_item->>'variant_id')::uuid and stock >= (v_item->>'qty')::int;
    get diagnostics v_rows = row_count;
    if v_rows = 0 then
      raise exception 'OUT_OF_STOCK:%', v_item->>'variant_id';
    end if;

    insert into order_items (order_id, product_id, variant_id, name, color, size, image_url, price, qty)
    values (v_id, (v_item->>'product_id')::uuid, (v_item->>'variant_id')::uuid, v_item->>'name',
            v_item->>'color', v_item->>'size', v_item->>'image_url',
            (v_item->>'price')::int, (v_item->>'qty')::int);
  end loop;

  -- COD counts coupon usage at placement (online counts at payment)
  if v_cod and v_coupon is not null then
    update coupons set used_count = used_count + 1
     where code = v_coupon and (usage_limit is null or used_count < usage_limit);
    get diagnostics v_rows = row_count;
    if v_rows = 0 then raise exception 'COUPON_LIMIT'; end if;
  end if;

  return jsonb_build_object('id', v_id, 'order_no', v_no);
end $$;

-- release_order_stock: puts stock back exactly once per order.
create or replace function release_order_stock(p_order_id uuid) returns boolean
language plpgsql security definer set search_path = public as $$
declare v_id uuid;
begin
  update orders set stock_released = true
   where id = p_order_id and not stock_released
  returning id into v_id;
  if v_id is null then return false; end if;

  update product_variants v
     set stock = v.stock + s.qty
    from (select variant_id, sum(qty)::int as qty from order_items
           where order_id = p_order_id and variant_id is not null group by variant_id) s
   where v.id = s.variant_id;
  return true;
end $$;

-- release_expired_orders: cancels unpaid online orders older than p_minutes.
create or replace function release_expired_orders(p_minutes int) returns int
language plpgsql security definer set search_path = public as $$
declare v_id uuid; n int := 0;
begin
  for v_id in
    select id from orders
     where status = 'pending_payment' and payment_status = 'pending'
       and created_at < now() - make_interval(mins => p_minutes)
     for update skip locked
  loop
    update orders set status = 'cancelled', payment_status = 'failed' where id = v_id;
    perform release_order_stock(v_id);
    n := n + 1;
  end loop;
  return n;
end $$;

-- mark_order_paid: idempotent. Returns the order id only the FIRST time.
create or replace function mark_order_paid(p_razorpay_order_id text, p_payment_id text) returns uuid
language plpgsql security definer set search_path = public as $$
declare v orders;
begin
  select * into v from orders where razorpay_order_id = p_razorpay_order_id for update;
  if not found or v.payment_status = 'paid' then return null; end if;

  update orders set
    payment_status      = 'paid',
    razorpay_payment_id = p_payment_id,
    paid_at             = now(),
    status              = case when status in ('pending_payment','cancelled') then 'confirmed' else status end,
    needs_review        = needs_review or v.stock_released,   -- paid after expiry → staff check stock
    coupon_counted      = coupon_counted or coupon_code is not null
  where id = v.id;

  if v.coupon_code is not null and not v.coupon_counted then
    update coupons set used_count = used_count + 1 where code = v.coupon_code;
  end if;
  return v.id;
end $$;

